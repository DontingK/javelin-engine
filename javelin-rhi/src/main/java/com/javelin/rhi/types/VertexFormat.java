package com.javelin.rhi.types;

/**
 * 顶点属性格式。
 */
public enum VertexFormat {
    R8_UNORM(1), R8_SNORM(1), R8_UINT(1), R8_SINT(1),
    R8G8_UNORM(2), R8G8_SNORM(2), R8G8_UINT(2), R8G8_SINT(2),
    R8G8B8_UNORM(3), R8G8B8_SNORM(3), R8G8B8_UINT(3), R8G8B8_SINT(3),
    R8G8B8A8_UNORM(4), R8G8B8A8_SNORM(4), R8G8B8A8_UINT(4), R8G8B8A8_SINT(4),
    R16_UNORM(2), R16_SNORM(2), R16_UINT(2), R16_SINT(2), R16_SFLOAT(2),
    R16G16_UNORM(4), R16G16_SNORM(4), R16G16_UINT(4), R16G16_SINT(4), R16G16_SFLOAT(4),
    R16G16B16_UNORM(6), R16G16B16_SNORM(6), R16G16B16_UINT(6), R16G16B16_SINT(6), R16G16B16_SFLOAT(6),
    R16G16B16A16_UNORM(8), R16G16B16A16_SNORM(8), R16G16B16A16_UINT(8), R16G16B16A16_SINT(8), R16G16B16A16_SFLOAT(8),
    R32_UINT(4), R32_SINT(4), R32_SFLOAT(4),
    R32G32_UINT(8), R32G32_SINT(8), R32G32_SFLOAT(8),
    R32G32B32_UINT(12), R32G32B32_SINT(12), R32G32B32_SFLOAT(12),
    R32G32B32A32_UINT(16), R32G32B32A32_SINT(16), R32G32B32A32_SFLOAT(16);

    private final int size;

    VertexFormat(int size) {
        this.size = size;
    }

    public int size() {
        return size;
    }
}
