package com.javelin.rhi.types;

/**
 * 像素格式。
 */
public enum Format {
    UNDEFINED,

    // 8-bit
    R8_UNORM, R8_SNORM, R8_UINT, R8_SINT,
    R8G8_UNORM, R8G8_SNORM, R8G8_UINT, R8G8_SINT,
    R8G8B8_UNORM, R8G8B8_SNORM, R8G8B8_UINT, R8G8B8_SINT,
    B8G8R8_UNORM, B8G8R8_SNORM, B8G8R8_UINT, B8G8R8_SINT,
    R8G8B8A8_UNORM, R8G8B8A8_SNORM, R8G8B8A8_UINT, R8G8B8A8_SINT, R8G8B8A8_SRGB,
    B8G8R8A8_UNORM, B8G8R8A8_SNORM, B8G8R8A8_UINT, B8G8R8A8_SINT, B8G8R8A8_SRGB,
    A8B8G8R8_UNORM_PACK32, A8B8G8R8_SRGB_PACK32,

    // 16-bit
    R16_UNORM, R16_SNORM, R16_UINT, R16_SINT, R16_SFLOAT,
    R16G16_UNORM, R16G16_SNORM, R16G16_UINT, R16G16_SINT, R16G16_SFLOAT,
    R16G16B16_UNORM, R16G16B16_SNORM, R16G16B16_UINT, R16G16B16_SINT, R16G16B16_SFLOAT,
    R16G16B16A16_UNORM, R16G16B16A16_SNORM, R16G16B16A16_UINT, R16G16B16A16_SINT, R16G16B16A16_SFLOAT,

    // 32-bit
    R32_UINT, R32_SINT, R32_SFLOAT,
    R32G32_UINT, R32G32_SINT, R32G32_SFLOAT,
    R32G32B32_UINT, R32G32B32_SINT, R32G32B32_SFLOAT,
    R32G32B32A32_UINT, R32G32B32A32_SINT, R32G32B32A32_SFLOAT,

    // Packed
    B10G11R11_UFLOAT_PACK32,
    E5B9G9R9_UFLOAT_PACK32,
    A2B10G10R10_UNORM_PACK32, A2B10G10R10_UINT_PACK32,
    A2R10G10B10_UNORM_PACK32, A2R10G10B10_UINT_PACK32,

    // Depth/Stencil
    D16_UNORM,
    D32_SFLOAT,
    S8_UINT,
    D16_UNORM_S8_UINT,
    D24_UNORM_S8_UINT,
    D32_SFLOAT_S8_UINT,

    // Compressed (BC)
    BC1_RGB_UNORM_BLOCK, BC1_RGB_SRGB_BLOCK,
    BC1_RGBA_UNORM_BLOCK, BC1_RGBA_SRGB_BLOCK,
    BC2_UNORM_BLOCK, BC2_SRGB_BLOCK,
    BC3_UNORM_BLOCK, BC3_SRGB_BLOCK,
    BC4_UNORM_BLOCK, BC4_SNORM_BLOCK,
    BC5_UNORM_BLOCK, BC5_SNORM_BLOCK,
    BC6H_UFLOAT_BLOCK, BC6H_SFLOAT_BLOCK,
    BC7_UNORM_BLOCK, BC7_SRGB_BLOCK;

    public int size() {
        return switch (this) {
            case R8_UNORM, R8_SNORM, R8_UINT, R8_SINT -> 1;
            case R8G8_UNORM, R8G8_SNORM, R8G8_UINT, R8G8_SINT, R16_UNORM, R16_SNORM, R16_UINT, R16_SINT, R16_SFLOAT -> 2;
            case R8G8B8_UNORM, R8G8B8_SNORM, R8G8B8_UINT, R8G8B8_SINT,
                 B8G8R8_UNORM, B8G8R8_SNORM, B8G8R8_UINT, B8G8R8_SINT -> 3;
            case R8G8B8A8_UNORM, R8G8B8A8_SNORM, R8G8B8A8_UINT, R8G8B8A8_SINT, R8G8B8A8_SRGB,
                 B8G8R8A8_UNORM, B8G8R8A8_SNORM, B8G8R8A8_UINT, B8G8R8A8_SINT, B8G8R8A8_SRGB,
                 A8B8G8R8_UNORM_PACK32, A8B8G8R8_SRGB_PACK32,
                 A2B10G10R10_UNORM_PACK32, A2B10G10R10_UINT_PACK32,
                 A2R10G10B10_UNORM_PACK32, A2R10G10B10_UINT_PACK32,
                 B10G11R11_UFLOAT_PACK32, E5B9G9R9_UFLOAT_PACK32,
                 R16G16_UNORM, R16G16_SNORM, R16G16_UINT, R16G16_SINT, R16G16_SFLOAT,
                 R32_UINT, R32_SINT, R32_SFLOAT -> 4;
            case R16G16B16_UNORM, R16G16B16_SNORM, R16G16B16_UINT, R16G16B16_SINT, R16G16B16_SFLOAT -> 6;
            case R16G16B16A16_UNORM, R16G16B16A16_SNORM, R16G16B16A16_UINT, R16G16B16A16_SINT, R16G16B16A16_SFLOAT,
                 R32G32_UINT, R32G32_SINT, R32G32_SFLOAT -> 8;
            case R32G32B32_UINT, R32G32B32_SINT, R32G32B32_SFLOAT -> 12;
            case R32G32B32A32_UINT, R32G32B32A32_SINT, R32G32B32A32_SFLOAT -> 16;
            case D16_UNORM, S8_UINT -> 2;
            case D32_SFLOAT -> 4;
            case D16_UNORM_S8_UINT -> 3;
            case D24_UNORM_S8_UINT -> 4;
            case D32_SFLOAT_S8_UINT -> 5;
            default -> throw new IllegalArgumentException("Compressed format size not supported: " + this);
        };
    }

    public boolean isDepth() {
        return switch (this) {
            case D16_UNORM, D32_SFLOAT, D16_UNORM_S8_UINT, D24_UNORM_S8_UINT, D32_SFLOAT_S8_UINT -> true;
            default -> false;
        };
    }

    public boolean isStencil() {
        return switch (this) {
            case S8_UINT, D16_UNORM_S8_UINT, D24_UNORM_S8_UINT, D32_SFLOAT_S8_UINT -> true;
            default -> false;
        };
    }

    public boolean isDepthOrStencil() {
        return isDepth() || isStencil();
    }
}
